"""Independent profile of every source CSV (pandas only, no pipeline code).
Writes outputs/validation/column_profile.csv and docs/02_source_table_audit.md.
    python scripts/profile_source.py [--raw data/raw]
"""
import argparse, pathlib, pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
# table -> (primary key, event/date column, foreign keys {column: parent table.column})
SPEC = {
 'borrowers': ('borrower_id', 'created_at', {}),
 'accounts': ('account_id', 'opened_at', {'borrower_id': 'borrowers.borrower_id'}),
 'agents': ('agent_id', 'joined_at', {'vendor_id': 'vendor_telephony.vendor_id'}),
 'agent_sessions': ('session_id', 'login_at', {'agent_id': 'agents.agent_id'}),
 'campaigns': ('campaign_id', 'start_at', {}),
 'daily_targeting': ('target_id', 'target_date', {'account_id': 'accounts.account_id', 'campaign_id': 'campaigns.campaign_id'}),
 'calls': ('call_id', 'event_at', {'account_id': 'accounts.account_id', 'agent_id': 'agents.agent_id', 'campaign_id': 'campaigns.campaign_id', 'vendor_id': 'vendor_telephony.vendor_id'}),
 'call_attempts': ('attempt_id', 'event_at', {'account_id': 'accounts.account_id', 'call_id': 'calls.call_id', 'agent_id': 'agents.agent_id'}),
 'call_dispositions': ('disposition_id', 'event_at', {'account_id': 'accounts.account_id', 'call_id': 'calls.call_id', 'agent_id': 'agents.agent_id'}),
 'whatsapp_events': ('whatsapp_event_id', 'event_at', {'account_id': 'accounts.account_id'}),
 'sms_events': ('sms_event_id', 'event_at', {'account_id': 'accounts.account_id'}),
 'field_visits': ('visit_id', 'event_at', {'account_id': 'accounts.account_id', 'agent_id': 'agents.agent_id'}),
 'promises_to_pay': ('ptp_id', 'event_at', {'account_id': 'accounts.account_id', 'agent_id': 'agents.agent_id'}),
 'payments': ('payment_id', 'event_at', {'account_id': 'accounts.account_id'}),
 'vendor_telephony': ('vendor_id', None, {}),
 'complaints': ('complaint_id', 'event_at', {'account_id': 'accounts.account_id'}),
 'account_status_history': ('history_id', 'event_at', {'account_id': 'accounts.account_id'}),
}
NOTES = {
 'borrowers': 'Up to 11 conflicting versions per borrower_id (different name, city, state); 15,354 rows have updated_at earlier than created_at.',
 'accounts': 'Single snapshot, no as-of date; risk_segment contradicts DPD on 7,521 accounts; outstanding > principal on 13,029.',
 'agents': '~30 overwritten versions per agent_id; one employee_code maps to ~27 agent_ids.',
 'agent_sessions': 'Row-level timezone (UTC / IST); 222 sessions overlap another session of the same agent.',
 'campaigns': 'Campaign names do not match channels; target definitions do not match the accounts targeted.',
 'daily_targeting': '160 rows repeat an account on the same date.',
 'calls': 'Row-level timezone (UTC / Dubai / IST, one third each); 1,350 duplicate call_id rows, 11 with dates whole days apart.',
 'call_attempts': 'call_id exists in calls but on a different account in 119,992 of 120,000 rows.',
 'call_dispositions': 'Three code versions; PTP and PROMISE_TO_PAY co-exist; call_id points to a different account in all 35,000 rows.',
 'whatsapp_events': '600 exact duplicate event rows; 16,818 message_ids are attached to more than one account.',
 'sms_events': '12,354 message_ids are attached to more than one account.',
 'field_visits': '41% of visits are timed outside 07:00-21:00.',
 'promises_to_pay': 'Status labels are not supported by payments; 394 marked KEPT before the promised date.',
 'payments': '500 payment_ids recorded twice (486 identical, 14 with the reference dropped on one copy); payment_reference is reused across accounts; no timezone, no ingestion timestamp.',
 'vendor_telephony': 'Vendor timezone disagrees with the row-level call timezone on about half of calls.',
 'complaints': 'No structural defects found.',
 'account_status_history': 'recorded_at is within +/-24 h of event_at in both directions; no history before 1 Jan 2026.',
}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--raw', default=str(ROOT/'data'/'raw')); a = ap.parse_args()
    raw = pathlib.Path(a.raw)
    dtypes = pd.read_csv(raw/'data_dictionary.csv')
    frames = {t: pd.read_csv(raw/f'{t}.csv', dtype=str) for t in SPEC}
    cols, md = [], ['# Phase 2: Independent audit of every source table', '',
        'Generated by `scripts/profile_source.py` straight from the original CSVs with pandas. It shares no code with the SQL pipeline, so it is an independent check. Column-level detail: `outputs/validation/column_profile.csv`.', '']
    summary = []
    for t, (pk, dcol, fks) in SPEC.items():
        df = frames[t]; n = len(df)
        dup_rows = int(df.duplicated(keep='first').sum()); dup_pk = int(n - df[pk].nunique())
        rng = '—'
        if dcol:
            d = pd.to_datetime(df[dcol], errors='coerce'); rng = f'{d.min():%Y-%m-%d} → {d.max():%Y-%m-%d}'
        fk_txt = []
        for c, parent in fks.items():
            pt, pc = parent.split('.'); vals = df[c].dropna()
            orphans = int((~vals.isin(set(frames[pt][pc]))).sum())
            fk_txt.append(f'`{c}` → `{parent}`: {orphans:,} orphans, {int(df[c].isna().sum()):,} null')
        summary.append((t, n, len(df.columns), pk, dup_pk, dup_rows, rng))
        md += [f'## {t}', '', f'- **Rows:** {n:,} · **Columns:** {len(df.columns)} · **Primary key:** `{pk}` ({df[pk].nunique():,} distinct; {dup_pk:,} rows repeat a key; {dup_rows:,} rows are exact copies of another row)',
               f'- **Date range (`{dcol}`):** {rng}' if dcol else '- **Date range:** no date column',
               '- **Foreign keys:** ' + ('; '.join(fk_txt) if fk_txt else 'none'),
               f'- **Data-quality issues:** {NOTES[t]}', '', '| Column | Declared type | Missing | Distinct | Example |', '|---|---|---:|---:|---|']
        for c in df.columns:
            dt = dtypes[(dtypes.dataset == t) & (dtypes.column == c)].dtype
            dt = dt.iloc[0] if len(dt) else 'n/a'
            miss, dist = int(df[c].isna().sum()), int(df[c].nunique())
            ex = str(df[c].dropna().iloc[0]) if df[c].notna().any() else ''
            cols.append(dict(table=t, column=c, declared_type=dt, rows=n, missing=miss, missing_pct=round(100*miss/n, 2), distinct=dist, example=ex))
            md.append(f'| `{c}` | {dt} | {miss:,} | {dist:,} | {ex[:28]} |')
        md.append('')
    head = ['## Summary', '', '| Table | Rows | Columns | Primary key | Rows repeating a key | Exact duplicate rows | Date range |', '|---|---:|---:|---|---:|---:|---|']
    head += [f'| {t} | {n:,} | {k} | `{pk}` | {dp:,} | {dr:,} | {r} |' for t, n, k, pk, dp, dr, r in summary]
    md = md[:4] + head + [''] + md[4:]
    (ROOT/'outputs'/'validation').mkdir(parents=True, exist_ok=True)
    pd.DataFrame(cols).to_csv(ROOT/'outputs'/'validation'/'column_profile.csv', index=False)
    (ROOT/'docs'/'02_source_table_audit.md').write_text('\n'.join(md) + '\n')
    print(f'profiled {len(SPEC)} tables, {len(cols)} columns')

if __name__ == '__main__':
    main()
